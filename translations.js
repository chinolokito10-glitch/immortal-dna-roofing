const normalize = (value) => value.trim().replace(/\s+/g, " ");

export function translate(value, locale = language) {
  if (locale !== "fr" || !value) return value;
  const key = normalize(value);
  let translated = french[key];
  if (translated === undefined) {
    if (/^(Learn more about|Call about) /.test(key))
      translated = key.replace(
        /^(Learn more about|Call about) (.+)$/,
        (_, action, service) =>
          `${action === "Call about" ? "Appeler pour" : "En savoir plus sur"} ${translate(service, locale)}`,
      );
    else if (key.startsWith("Ask about roofing in "))
      translated = key.replace(
        "Ask about roofing in ",
        "Se renseigner sur les toitures à ",
      );
    else if (key.startsWith("Homeowner, "))
      translated = key.replace("Homeowner, ", "Propriétaire, ");
    else if (/^\d+(\.\d+)? out of 5 stars$/.test(key))
      translated = key.replace("out of 5 stars", "sur 5 étoiles");
    else if (key.startsWith("Privacy contact: "))
      translated = key
        .replace("Privacy contact: ", "Responsable de la confidentialité : ")
        .replace("[EMAIL]", "[COURRIEL]")
        .replace(
          "The company must confirm how to request access, correction, or deletion, and publish its final privacy terms.",
          "L’entreprise doit préciser comment demander l’accès, la correction ou la suppression des renseignements et publier sa politique finale.",
        );
    else if (key.startsWith("Company: "))
      translated = key
        .replace("Company: ", "Entreprise : ")
        .replace(
          "Roofing Co. (editable concept). Contact:",
          "Toitures (concept modifiable). Contact :",
        )
        .replace("[EMAIL]", "[COURRIEL]");
    else if (key.startsWith("Delivery could not be confirmed. ")) {
      const detail = key
        .slice("Delivery could not be confirmed. ".length)
        .replace(" Your details are still here; you can download a copy.", "");
      translated = `L’envoi n’a pas pu être confirmé. ${french[detail] || "Le service est indisponible. Veuillez réessayer."} Vos renseignements sont conservés dans le formulaire; vous pouvez en télécharger une copie.`;
    } else if (/^Call [ +\d(]/.test(key))
      translated = key.replace(/^Call /, "Appelez le ");
  }
  if (translated === undefined) return value;
  return value.replace(/\S[\s\S]*\S|\S/, translated);
}

export function initLanguageSwitch() {
  const button = document.querySelector(".language-toggle");
  const originals = new WeakMap();
  const attributes = new WeakMap();
  const translatedAttributes = [
    "aria-label",
    "alt",
    "placeholder",
    "title",
    "content",
  ];
  const excluded =
    "script, style, noscript, .language-toggle, textarea, input, [data-company], .footer-wordmark";

  // Options without an explicit value derive their value from their label.
  // Pin English values so changing language cannot change the API contract.
  document.querySelectorAll("select option").forEach((option) => {
    if (!option.hasAttribute("value")) option.value = option.textContent;
  });

  function apply() {
    observer.disconnect();
    const walker = document.createTreeWalker(
      document.documentElement,
      NodeFilter.SHOW_TEXT,
    );
    while (walker.nextNode()) {
      const node = walker.currentNode;
      if (
        !node.parentElement ||
        node.parentElement.closest(excluded) ||
        !node.textContent.trim()
      )
        continue;
      let record = originals.get(node);
      if (!record || node.textContent !== record.last)
        record = { english: node.textContent };
      const next = translate(record.english);
      if (node.textContent !== next) node.textContent = next;
      record.last = next;
      originals.set(node, record);
    }
    document
      .querySelectorAll(
        "[aria-label], [alt], [placeholder], [title], meta[content]",
      )
      .forEach((element) => {
        if (element.closest(".language-toggle")) return;
        const saved = attributes.get(element) || {};
        for (const name of translatedAttributes) {
          if (!element.hasAttribute(name)) continue;
          const current = element.getAttribute(name);
          if (!saved[name] || current !== saved[name].last)
            saved[name] = { english: current };
          const next = translate(saved[name].english);
          if (current !== next) element.setAttribute(name, next);
          saved[name].last = next;
        }
        attributes.set(element, saved);
      });
    document.documentElement.lang = language;
    button.textContent = language === "en" ? "FR" : "EN";
    button.lang = language === "en" ? "fr" : "en";
    const label =
      language === "en" ? "Passer en français" : "Switch to English";
    button.setAttribute("aria-label", label);
    button.title = label;
    observer.observe(document.documentElement, {
      subtree: true,
      childList: true,
      characterData: true,
      attributes: true,
      attributeFilter: translatedAttributes,
    });
  }
  // Covers asynchronously rendered dialogs, request statuses, and labels.
  const observer = new MutationObserver(apply);
  try {
    language =
      localStorage.getItem("northline-language") === "fr" ? "fr" : "en";
  } catch {
    /* Storage may be blocked; toggling still works. */
  }
  button.addEventListener("click", () => {
    language = language === "en" ? "fr" : "en";
    try {
      localStorage.setItem("northline-language", language);
    } catch {
      /* Session-only preference. */
    }
    apply();
  });
  apply();
}
